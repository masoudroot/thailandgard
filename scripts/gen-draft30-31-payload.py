def payload(d):
    ops = [{
        "op": "guide.insert", "slug": d["slug"], "title": d["title"],
        "excerpt": d["excerpt"], "category": d["category"],
        "reading_minutes": d["reading_minutes"], "updated_fa": d["updated_fa"],
    }]
    for i, (heading, paragraphs) in enumerate(d["sections"], 1):
        ops.append({"op": "guide_section.insert", "guide_slug": d["slug"],
                    "position": i, "heading": heading, "paragraphs": paragraphs})
    for i, (q, a) in enumerate(d.get("faqs", []), 1):
        ops.append({"op": "guide_faq.insert", "guide_slug": d["slug"],
                    "position": i, "question": q, "answer": a})
    return {"dry_run": False, "ops": ops}


