/**
 * تورهای یک دسته را از روی دادهٔ زنده برمی‌گرداند.
 * - tourSlugs: همان تورها به همان ترتیب (فقط فعال‌ها)
 * - cities: تورهایی که route یا shortTitle شامل شهر(ها) باشد؛
 *   برای combo با دو شهر، هر دو شهر باید باشند
 * - هیچ‌کدام: همهٔ تورهای فعال
 * مرتب‌سازی: قیمت به‌روز (isPriceFresh) اول، بعد ارزان‌تر اول،
 * تور بدون قیمت آخر.
 */
export function getCategoryTours(
  category: TourCategory,
  tours: Tour[],
  now: number = Date.now(),
): Tour[] {
  let matched: Tour[];

  if (category.tourSlugs && category.tourSlugs.length > 0) {
    const bySlug = new Map(tours.map((t) => [t.slug, t]));
    matched = category.tourSlugs
      .map((s) => bySlug.get(s))
      .filter((t): t is Tour => t !== undefined && t.active);
  } else if (category.cities && category.cities.length > 0) {
    const cities = category.cities;
    const requireAll = category.kind === "combo" && cities.length >= 2;
    matched = tours.filter((t) => {
      if (!t.active) return false;
      const haystack = `${t.route} ${t.shortTitle}`;
      return requireAll
        ? cities.every((c) => haystack.includes(c))
        : cities.some((c) => haystack.includes(c));
    });
  } else {
    matched = tours.filter((t) => t.active);
  }

  return matched.sort((a, b) => {
    const aFresh = isPriceFresh(a.priceFrom, a.priceUpdatedAt, now);
    const bFresh = isPriceFresh(b.priceFrom, b.priceUpdatedAt, now);
    if (aFresh !== bFresh) return aFresh ? -1 : 1;
    if (a.priceFrom == null && b.priceFrom == null) return 0;
    if (a.priceFrom == null) return 1;
    if (b.priceFrom == null) return -1;
    return a.priceFrom - b.priceFrom;
  });
}

/**
 * پوشش کش‌شدهٔ getCategoryTours برای مسیرهای استاتیک (الگوی isPriceFreshCached
 * در lib/tours.ts): مقدار Date.now فقط داخل «use cache» خوانده می‌شود تا در
 * پرریرندر محاسبه و کش شود و روت کاملاً استاتیک بماند. با هر دیپلوی مقدار
 * تازه محاسبه می‌شود که با ریتم انتشار پیوستهٔ سایت همان تازگی موردنظر است.
 */
export async function getCategoryToursCached(category: TourCategory): Promise<Tour[]> {
  "use cache";
  const tours = await getTours();
  return getCategoryTours(category, tours, Date.now());
}
