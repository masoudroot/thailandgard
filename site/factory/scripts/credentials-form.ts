type EnvValues = Record<string, string>;

interface RestartResult {
  projector: boolean;
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function unquote(value: string): string {
  const trimmed = value.trim();
  if (
    (trimmed.startsWith('"') && trimmed.endsWith('"')) ||
    (trimmed.startsWith("'") && trimmed.endsWith("'"))
  ) {
    return trimmed
      .slice(1, -1)
      .replace(/\\"/g, '"')
      .replace(/\\\\/g, '\\');
  }
  return trimmed;
}

function readEnvFile(): EnvValues {
  if (!existsSync(ENV_PATH)) return {};
  const values: EnvValues = {};
  for (const rawLine of readFileSync(ENV_PATH, 'utf8').split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const match = line.match(
      /^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/,
    );
    if (!match) continue;
    values[match[1]] = unquote(match[2]);
  }
  return values;
}

function quoteEnv(value: string): string {
  if (/^[A-Za-z0-9_./:@+\-=,]+$/.test(value)) return value;
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

function buildEnvFile(values: EnvValues): string {
  const lines = [
    '# Generated by factory:credentials. Do not commit this file.',
    '# Local only. Secrets stay on this machine.',
    '',
    '# --- Supabase ---',
  ];
  const add = (key: string): void => {
    const value = values[key];
    if (value === undefined || value === '') return;
    lines.push(`${key}=${quoteEnv(value)}`);
  };
  const addAll = (keys: string[]): void => {
    for (const key of keys) add(key);
  };

  addAll(['SUPABASE_URL', 'SUPABASE_SERVICE_ROLE_KEY']);
  lines.push('', '# --- Google Search Console ---');
  addAll(['GSC_SERVICE_ACCOUNT_JSON', 'GSC_SITE_URL']);
  lines.push('', '# --- LLM ---');
  addAll(['LLM_API_BASE', 'LLM_API_KEY']);
  lines.push('', '# --- SEO R1 gate ---');
  addAll(['SERPAPI_API_KEY', 'FACTORY_PREVIEW_BASE_URL']);
  lines.push('', '# --- Factory local ---');
  addAll([
    'FACTORY_ENV',
    'FACTORY_DATABASE_URL',
    'FACTORY_CONTROL_TOKEN',
    'FACTORY_EVIDENCE_SECRET',
  ]);
  lines.push('', '# --- Artifact storage ---');
  addAll([
    'FACTORY_ARTIFACT_DIR',
    'FACTORY_ARTIFACT_ENDPOINT',
    'FACTORY_ARTIFACT_REGION',
    'FACTORY_ARTIFACT_BUCKET',
    'FACTORY_ARTIFACT_ACCESS_KEY_ID',
    'FACTORY_ARTIFACT_SECRET_ACCESS_KEY',
  ]);
  lines.push('', '# --- Outreach (dry-run unless live is true) ---');
  addAll([
    'FACTORY_OUTREACH_LIVE',
    'RESEND_API_KEY',
    'FACTORY_OUTREACH_FROM_EMAIL',
    'FACTORY_OUTREACH_UNSUBSCRIBE_BASE',
  ]);
  return `${lines.join('\n')}\n`;
}

function normalizeGsc(value: string): string {
  const trimmed = value.trim();
  if (!trimmed) throw new Error('GSC_SERVICE_ACCOUNT_JSON is required');

  if (trimmed.startsWith('{')) {
    let parsed: unknown;
    try {
      parsed = JSON.parse(trimmed);
    } catch {
      throw new Error('GSC JSON is not valid JSON');
    }
    if (
      !isRecord(parsed) ||
      typeof parsed.client_email !== 'string' ||
      typeof parsed.private_key !== 'string'
    ) {
      throw new Error('GSC JSON must contain client_email and private_key');
    }
    return Buffer.from(JSON.stringify(parsed), 'utf8').toString('base64');
  }

  const compact = trimmed.replace(/\s+/g, '');
  let parsed: unknown;
  try {
    parsed = JSON.parse(Buffer.from(compact, 'base64').toString('utf8'));
  } catch {
    throw new Error('GSC value is neither JSON nor valid base64 JSON');
  }
  if (
    !isRecord(parsed) ||
    typeof parsed.client_email !== 'string' ||
    typeof parsed.private_key !== 'string'
  ) {
    throw new Error('GSC base64 must decode to a service account JSON');
  }
  return compact;
}

function validateUrl(value: string, key: string): void {
  try {
    const url = new URL(value);
    if (url.protocol !== 'http:' && url.protocol !== 'https:') {
      throw new Error('protocol');
    }
  } catch {
    throw new Error(`${key} must be an http(s) URL`);
  }
}

function normalizeAndValidate(input: EnvValues): EnvValues {
  const values: EnvValues = {
    ...DEFAULTS,
    ...readEnvFile(),
    ...input,
  };

  for (const key of REQUIRED) {
    if (!values[key]?.trim()) {
      throw new Error(`missing:${key}`);
    }
  }

  values.SUPABASE_URL = values.SUPABASE_URL.trim().replace(/\/+$/, '');
  validateUrl(values.SUPABASE_URL, 'SUPABASE_URL');
  values.SUPABASE_SERVICE_ROLE_KEY = values.SUPABASE_SERVICE_ROLE_KEY.trim();
  values.GSC_SERVICE_ACCOUNT_JSON = normalizeGsc(values.GSC_SERVICE_ACCOUNT_JSON);
  values.GSC_SITE_URL = values.GSC_SITE_URL.trim();
  values.LLM_API_BASE = values.LLM_API_BASE.trim().replace(/\/+$/, '');
  validateUrl(values.LLM_API_BASE, 'LLM_API_BASE');
  values.LLM_API_KEY = values.LLM_API_KEY.trim();
  values.FACTORY_PREVIEW_BASE_URL = values.FACTORY_PREVIEW_BASE_URL
    .trim()
    .replace(/\/+$/, '');
  validateUrl(values.FACTORY_PREVIEW_BASE_URL, 'FACTORY_PREVIEW_BASE_URL');

  if (values.FACTORY_OUTREACH_LIVE === 'true') {
    const outreachRequired = [
      'RESEND_API_KEY',
      'FACTORY_OUTREACH_FROM_EMAIL',
      'FACTORY_OUTREACH_UNSUBSCRIBE_BASE',
    ];
    for (const key of outreachRequired) {
      if (!values[key]?.trim()) throw new Error(`missing:${key}`);
    }
  }

  return values;
}

function pickStrings(input: Record<string, unknown>): EnvValues {
  const values: EnvValues = {};
  for (const key of WRITE_ORDER) {
    const raw = input[key];
    if (typeof raw === 'string') values[key] = raw.trim();
    else if (typeof raw === 'boolean') values[key] = raw ? 'true' : 'false';
  }
  return values;
}

function sendJson(
  response: ServerResponse,
  status: number,
  payload: unknown,
): void {
  response.writeHead(status, {
    'content-type': 'application/json; charset=utf-8',
    'cache-control': 'no-store',
    'x-content-type-options': 'nosniff',
  });
  response.end(JSON.stringify(payload));
}

function sendHtml(response: ServerResponse): void {
  try {
    const html = readFileSync(HTML_PATH, 'utf8');
    response.writeHead(200, {
      'content-type': 'text/html; charset=utf-8',
      'cache-control': 'no-store',
      'x-content-type-options': 'nosniff',
    });
    response.end(html);
  } catch {
    response.writeHead(500, { 'content-type': 'text/plain; charset=utf-8' });
    response.end(`UI not found: ${HTML_PATH}`);
  }
}

async function readJsonBody(request: IncomingMessage): Promise<unknown> {
  return new Promise((resolveBody, reject) => {
    let body = '';
    let settled = false;
    const fail = (error: Error): void => {
      if (settled) return;
      settled = true;
      reject(error);
    };
    request.on('data', (chunk: Buffer) => {
      body += chunk.toString('utf8');
      if (body.length > 1_000_000) {
        fail(new Error('body too large'));
        request.destroy();
      }
    });
    request.on('end', () => {
      if (settled) return;
      settled = true;
      try {
        resolveBody(body ? JSON.parse(body) : {});
      } catch {
        reject(new Error('invalid JSON'));
      }
    });
    request.on('error', (error) => fail(error));
  });
}

function powershellQuote(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

async function runPowerShell(script: string): Promise<string> {
  const { stdout } = await execFileAsync(
    'powershell.exe',
    ['-NoLogo', '-NoProfile', '-NonInteractive', '-Command', script],
    { windowsHide: true, timeout: 30_000 },
  );
  return stdout.trim();
}

function restartScripts(): { projectorLog: string; projectorErr: string } {
  const logDir = resolve(tmpdir(), 'opencode');
  mkdirSync(logDir, { recursive: true });
  return {
    projectorLog: resolve(logDir, 'factory-projector.log'),
    projectorErr: resolve(logDir, 'factory-projector.err.log'),
  };
}

async function restartWorkers(): Promise<RestartResult> {
  const logs = restartScripts();
  const kill = `$targets = Get-CimInstance Win32_Process -Filter "Name = 'node.exe'" | Where-Object { $_.CommandLine -match 'projector\\.ts' }; foreach ($t in $targets) { Stop-Process -Id $t.ProcessId -Force -ErrorAction SilentlyContinue }`;
  await runPowerShell(kill);

  const start = [
    `Start-Process -FilePath 'cmd.exe' -ArgumentList '/c','npm run factory:projector' -WorkingDirectory ${powershellQuote(SITE_ROOT)} -RedirectStandardOutput ${powershellQuote(logs.projectorLog)} -RedirectStandardError ${powershellQuote(logs.projectorErr)} -WindowStyle Hidden`,
  ].join('; ');
  await runPowerShell(start);

  const check = `$p = @(Get-CimInstance Win32_Process -Filter "Name = 'node.exe'" | Where-Object { $_.CommandLine -match 'projector\\.ts' }).Count; Write-Output "$p"`;

  const deadline = Date.now() + 15_000;
  let projector = false;
  while (Date.now() < deadline) {
    await new Promise((resolveWait) => setTimeout(resolveWait, 1_000));
    const output = await runPowerShell(check);
    const projectorCount = Number(output);
    projector = Number.isFinite(projectorCount) && projectorCount > 0;
    if (projector) break;
  }
  return { projector };
}

function relativeEnvPath(): string {
  const path = relative(SITE_ROOT, ENV_PATH);
  return path.startsWith('..') ? ENV_PATH : path;
}

async function handleSave(
  request: IncomingMessage,
  response: ServerResponse,
): Promise<void> {
  const body = await readJsonBody(request);
  if (!isRecord(body) || !isRecord(body.values)) {
    sendJson(response, 400, { ok: false, error: 'invalid payload' });
    return;
  }

  const input = pickStrings(body.values);
  let values: EnvValues;
  try {
    values = normalizeAndValidate(input);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    if (message.startsWith('missing:')) {
      const missing = message.slice('missing:'.length).split(',');
      sendJson(response, 400, { ok: false, missing });
    } else {
      sendJson(response, 400, { ok: false, error: message });
    }
    return;
  }

  writeFileSync(ENV_PATH, buildEnvFile(values), 'utf8');
  const restart = body.restart === true;
  const result = restart ? await restartWorkers() : undefined;
  sendJson(response, 200, {
    ok: true,
    envFile: relativeEnvPath(),
    restart: result,
  });
}

const server = createServer((request, response) => {
  void (async () => {
    try {
      const url = new URL(
        request.url ?? '/',
        `http://127.0.0.1:${String(PORT)}`,
      );
      if (request.method === 'GET' && url.pathname === '/') {
        sendHtml(response);
        return;
      }
      if (request.method === 'GET' && url.pathname === '/api/state') {
        sendJson(response, 200, {
          ok: true,
          exists: existsSync(ENV_PATH),
          envFile: relativeEnvPath(),
          values: { ...DEFAULTS, ...readEnvFile() },
        });
        return;
      }
      if (request.method === 'POST' && url.pathname === '/api/save') {
        await handleSave(request, response);
        return;
      }
      if (request.method === 'POST' && url.pathname === '/api/restart') {
        const restart = await restartWorkers();
        sendJson(response, 200, { ok: true, restart });
        return;
      }
      if (request.method === 'GET' && url.pathname === '/api/health') {
        sendJson(response, 200, { ok: true });
        return;
      }
      sendJson(response, 404, { ok: false, error: 'not found' });
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error);
      sendJson(response, 500, { ok: false, error: message });
    }
  })();
});

server.listen(PORT, '127.0.0.1', () => {
  logger.info(`credentials form: http://127.0.0.1:${String(PORT)}`);
  logger.info(`env file: ${relativeEnvPath()}`);
});
