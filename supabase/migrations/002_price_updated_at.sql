-- ============================================================================
-- مهاجرت 002: ستون تاریخ به‌روزرسانی قیمت روی تورها
-- Migration 002: price_updated_at on tours
--
-- زمینه (بریف آمیتیس، حکم مدیر ۰۳:۴۰، ۲۰ مهر ۱۴۰۵): اقدام ۱ بریف آمیتیس
-- («قیمت تور چقدر است؟» در FAQ صفحه‌های تور) معلق است چون جدول tours هیچ
-- ستون تاریخ به‌روزرسانی ندارد و «همان منطق تازگی نمایشی» منبعی نداشت.
-- این مایگریشنِ افزایشی (expand) ستون را می‌سازد؛ بک‌فیل NULL یعنی «نامشخصِ
-- صادقانه» (قانون مدیر: عدد «شروع قیمت از» + تاریخ، یا «نامشخص»).
--
-- Idempotent: اجرای چندباره امن است (ADD COLUMN IF NOT EXISTS).
-- افزایشیِ خالص: هیچ ستونی حذف/تغییر نمی‌کند؛ کد قدیم/جدید هر دو کار می‌کنند.
--
-- ⚠️ اجرا: این فایل را با نقش service_role (داشبورد Supabase ← SQL Editor)
-- اجرا کنید؛ کلید anon ایجنت‌ها دسترسی DDL ندارد.
-- پس از اجرا: راستی‌آزمایی با
--   select column_name, data_type, is_nullable from information_schema.columns
--   where table_name = 'tours' and column_name = 'price_updated_at';
-- و سپس اقدام ۱ از تعلیق درمی‌آید (مالک: dev).
-- ============================================================================

alter table public.tours
  add column if not exists price_updated_at timestamptz null;

comment on column public.tours.price_updated_at is
  'تاریخ آخرین به‌روزرسانی قیمت (شروع قیمت)؛ NULL یعنی نامشخص (قانون تازگی قیمت مدیر)';
